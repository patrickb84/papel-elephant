// Review tool for the content pipeline.
//
//   node scripts/review.ts                    write content/REVIEW.md (everything awaiting a decision)
//   node scripts/review.ts approve lines 1342 2701 [--by "Name"] [--note "..."]
//   node scripts/review.ts reject  art 1342 --note "portrait of a stranger"
//   node scripts/review.ts approve portraits 1342
//   node scripts/review.ts contact-sheet [gutenbergId ...]   JPG grids of the chosen paintings in .cache/contact/
//
// Approvals are tied to what was approved: a line approval stores the hash of
// the exact sentence, an artwork approval stores museum:id. If the pipeline
// later produces something different, the old approval no longer applies.
// The reviewer name defaults to $REVIEWER, else "editor".

import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';
import { CACHE_DIR, FILES, ROOT } from './lib/paths.ts';
import { fetchBuffer } from './lib/http.ts';
import type { ArtResult, Candidate, ImagesResult, LineResult, MetadataResult, Review, Reviews } from './lib/types.ts';
import { loadOverrides, loadReviews, readJson, writeJson } from './lib/util.ts';

const args = process.argv.slice(2);
const flag = (name: string) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 ? args.splice(i, 2)[1] : undefined;
};
const by = flag('by') ?? process.env.REVIEWER ?? 'editor';
const note = flag('note');
const [command = 'sheet', kind, ...rest] = args;
const ids = (command === 'contact-sheet' || command === 'candidates' ? [kind, ...rest] : rest).filter(Boolean).map(Number).filter(Boolean);

async function load() {
  return {
    candidates: await readJson<Candidate[]>(FILES.candidates),
    lines: new Map((await readJson<LineResult[]>(FILES.lines, [])).map((r) => [r.gutenbergId, r])),
    meta: new Map((await readJson<MetadataResult[]>(FILES.metadata, [])).map((r) => [r.gutenbergId, r])),
    art: new Map((await readJson<ArtResult[]>(FILES.artwork, [])).map((r) => [r.gutenbergId, r])),
    images: new Map((await readJson<ImagesResult[]>(FILES.images, [])).map((r) => [r.gutenbergId, r])),
    overrides: await loadOverrides(),
    reviews: await loadReviews(),
  };
}

async function decide(status: Review['status']) {
  if (!['lines', 'art', 'portraits'].includes(kind) || !ids.length) {
    console.error('usage: node scripts/review.ts approve|reject lines|art|portraits <gutenbergId ...> [--by name] [--note text]');
    process.exit(1);
  }
  const d = await load();
  const reviews: Reviews = d.reviews;
  const date = new Date().toISOString().slice(0, 10);
  for (const id of ids) {
    let ref: string | undefined;
    if (kind === 'lines') ref = d.lines.get(id)?.hash;
    if (kind === 'art') ref = d.art.get(id)?.chosen && `${d.art.get(id)!.chosen!.museum}:${d.art.get(id)!.chosen!.id}`;
    if (kind === 'portraits') ref = d.meta.get(id)?.author?.portrait?.file;
    if (!ref) {
      console.warn(`  ${id}: nothing to review for ${kind}`);
      continue;
    }
    reviews[kind as keyof Reviews][String(id)] = { status, ref, by, date, ...(note ? { note } : {}) };
    console.log(`  ${status} ${kind} ${id}`);
  }
  await writeJson(FILES.reviews, reviews);
}

async function sheet() {
  const d = await load();
  const out: string[] = [
    '# Review sheet',
    '',
    'Generated by `npm run content:review`. Approve with `node scripts/review.ts approve lines|art|portraits <ids>`;',
    'reject with `reject` and a `--note`. To fix a line or swap a painting, edit `content/overrides.json` and re-run the pipeline.',
    '',
  ];
  let pending = 0;
  for (const c of d.candidates) {
    const key = String(c.gutenbergId);
    if (d.overrides.exclude[key]) continue;
    const L = d.lines.get(c.gutenbergId), M = d.meta.get(c.gutenbergId), A = d.art.get(c.gutenbergId);
    const lr = d.reviews.lines[key], ar = d.reviews.art[key];
    const lineDone = lr && lr.ref === L?.hash;
    const artDone = ar && A?.chosen && ar.ref === `${A.chosen.museum}:${A.chosen.id}`;
    if (lineDone && (artDone || A?.confidence === 'high')) continue;
    pending++;
    out.push(`## ${c.title} (#${c.gutenbergId}, ${M?.year ?? 'no year'})`, '');
    if (!lineDone) {
      out.push(`**Line** [${L?.confidence ?? 'failed'}] ${L?.flags.join(', ') ?? ''}`, '');
      out.push(`> ${L?.sentence ?? L?.error ?? 'not extracted'}`, '');
      if (L?.anchor) out.push(`Found under: \`${L.anchor}\` · before it: ${L.context ?? ''}`, '');
      if (M?.wikidataFirstLine) out.push(`Wikidata first line: ${M.wikidataFirstLine}`, '');
    }
    if (A?.chosen && !artDone) {
      const ch = A.chosen;
      out.push(`**Art** [${A.confidence}] ${A.flags.join(', ')} · themes: ${A.themes.join(', ')}`, '');
      out.push(`[${ch.title}](${ch.sourceUrl}) - ${ch.artist}, ${ch.date} (${ch.museum}:${ch.id}) · ${(ch.reasons ?? []).join('; ')}`, '');
      if (A.alternates.length) out.push('Alternates: ' + A.alternates.map((x) => `[${x.title}](${x.sourceUrl}) ${x.date} \`${x.museum}:${x.id}\``).join(' · '), '');
    }
  }
  out.splice(5, 0, `${pending} books awaiting a decision.`, '');
  await writeFile(FILES.reviewSheet, out.join('\n'), 'utf8');
  console.log(`${pending} books awaiting review - see ${path.relative(ROOT, FILES.reviewSheet)}`);
}

const esc = (s: string) => s.replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]!);

async function contactSheet() {
  const d = await load();
  const rows = d.candidates.filter((c) => d.images.get(c.gutenbergId)?.artwork && (!ids.length || ids.includes(c.gutenbergId)));
  const dir = path.join(CACHE_DIR, 'contact');
  await mkdir(dir, { recursive: true });
  const cell = 300, label = 56, cols = 4, perSheet = 16;
  for (let s = 0; s * perSheet < rows.length; s++) {
    const page = rows.slice(s * perSheet, (s + 1) * perSheet);
    const height = Math.ceil(page.length / cols) * (cell + label);
    const composites = [];
    for (const [i, c] of page.entries()) {
      const img = d.images.get(c.gutenbergId)!.artwork!;
      const A = d.art.get(c.gutenbergId)!;
      const x = (i % cols) * cell, y = Math.floor(i / cols) * (cell + label);
      const buf = await sharp(path.join(ROOT, 'public', img.srcSmall)).resize(cell, cell, { fit: 'contain', background: '#ffffff' }).toBuffer();
      composites.push({ input: buf, left: x, top: y });
      const text = `<svg width="${cell}" height="${label}"><rect width="100%" height="100%" fill="#fff"/>
        <text x="6" y="18" font-family="Arial" font-size="13" font-weight="bold">${esc(`${c.gutenbergId} ${c.title}`.slice(0, 40))} (${d.meta.get(c.gutenbergId)?.year})</text>
        <text x="6" y="36" font-family="Arial" font-size="12">${esc(`${A.chosen!.title}`.slice(0, 44))}</text>
        <text x="6" y="51" font-family="Arial" font-size="11" fill="#666">${esc(`${A.chosen!.date} · ${A.confidence} · ${A.flags.join(' ')}`.slice(0, 48))}</text></svg>`;
      composites.push({ input: Buffer.from(text), left: x, top: y + cell });
    }
    const file = path.join(dir, `sheet-${String(s + 1).padStart(2, '0')}.jpg`);
    await sharp({ create: { width: cols * cell, height, channels: 3, background: '#ffffff' } }).composite(composites).jpeg({ quality: 78 }).toFile(file);
    console.log(file);
  }
}

/** A small preview URL for a candidate (Met web-large / AIC 400px IIIF). */
const previewUrl = (imageUrl: string) =>
  imageUrl.replace('/CRDImages/', '/CRDImages/').replace('/original/', '/web-large/').replace('/full/1686,/', '/full/400,/');

/** One sheet per book: the chosen painting and its alternates, labelled with museum:id for overrides. */
async function candidateSheets() {
  const d = await load();
  const dir = path.join(CACHE_DIR, 'contact');
  await mkdir(dir, { recursive: true });
  const cell = 240, label = 62, cols = 4;
  for (const c of d.candidates.filter((x) => !ids.length || ids.includes(x.gutenbergId))) {
    const A = d.art.get(c.gutenbergId);
    if (!A?.chosen) continue;
    const options = [A.chosen, ...A.alternates].slice(0, 12);
    const composites = [];
    for (const [i, o] of options.entries()) {
      const x = (i % cols) * cell, y = Math.floor(i / cols) * (cell + label);
      try {
        const buf = await fetchBuffer(previewUrl(o.imageUrl), { timeout: 60_000 });
        composites.push({ input: await sharp(buf).resize(cell - 8, cell - 8, { fit: 'contain', background: '#ffffff' }).toBuffer(), left: x + 4, top: y + 4 });
      } catch {
        /* leave the cell blank */
      }
      const text = `<svg width="${cell}" height="${label}"><rect width="100%" height="100%" fill="${i === 0 ? '#fff3cf' : '#fff'}"/>
        <text x="6" y="16" font-family="Arial" font-size="12" font-weight="bold">${i === 0 ? 'CHOSEN ' : ''}${o.museum}:${o.id} · score ${o.score}</text>
        <text x="6" y="33" font-family="Arial" font-size="12">${esc(o.title.slice(0, 40))}</text>
        <text x="6" y="50" font-family="Arial" font-size="11" fill="#555">${esc(`${o.artist}, ${o.date}`.slice(0, 44))}</text></svg>`;
      composites.push({ input: Buffer.from(text), left: x, top: y + cell });
    }
    const height = Math.ceil(options.length / cols) * (cell + label) + 30;
    const head = `<svg width="${cols * cell}" height="30"><rect width="100%" height="100%" fill="#222"/><text x="8" y="20" font-family="Arial" font-size="15" fill="#fff">${esc(`${c.gutenbergId} ${c.title} (${d.meta.get(c.gutenbergId)?.year}) · themes: ${A.themes.join(', ')}`)}</text></svg>`;
    const file = path.join(dir, `candidates-${c.gutenbergId}.jpg`);
    await sharp({ create: { width: cols * cell, height, channels: 3, background: '#ffffff' } })
      .composite([{ input: Buffer.from(head), left: 0, top: 0 }, ...composites.map((x) => ({ ...x, top: x.top + 30 }))])
      .jpeg({ quality: 80 }).toFile(file);
    console.log(file);
  }
}

if (command === 'approve') await decide('approved');
else if (command === 'reject') await decide('rejected');
else if (command === 'contact-sheet') await contactSheet();
else if (command === 'candidates') await candidateSheets();
else await sheet();
